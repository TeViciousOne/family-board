/* Builds css/dark.css: the rules the style sheets apply when the device is dark, repeated for <html data-theme="dark">,
   so Settings > Look can force a dark theme on a device that is set to light.
   Run after changing any "@media (prefers-color-scheme: dark)" block:   node scripts/dark-css.js        (check only: node scripts/dark-css.js check) */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'css');
let out = '/* GENERATED by scripts/dark-css.js from the "prefers-color-scheme: dark" blocks of ios.css, glass.css and look.css.\n   Edit those blocks and run the script again; do not edit this file. */\n';
for (const f of ['ios.css', 'glass.css', 'look.css']) {
  const c = fs.readFileSync(path.join(dir, f), 'utf8');
  let i = 0;
  for (;;) {
    const j = c.indexOf('@media (prefers-color-scheme: dark)', i);
    if (j < 0) break;
    const k = c.indexOf('{', j);
    let depth = 1, p = k + 1;
    while (depth) { if (c[p] === '{') depth++; else if (c[p] === '}') depth--; p++; }
    i = p;
    const inner = c.slice(k + 1, p - 1), re = /([^{}]+)\{([^{}]*)\}/g;
    let m;
    while ((m = re.exec(inner))) {
      const sels = m[1].trim().split(',').map((s) => {
        s = s.trim();
        if (s.includes(':root:not([data-theme="light"])')) return s.split(':root:not([data-theme="light"])').join(':root[data-theme="dark"]');
        return s === 'html' ? 'html[data-theme="dark"]' : ':root[data-theme="dark"] ' + s;
      });
      out += sels.join(', ') + ' {' + m[2].trim().split(/\s+/).join(' ') + '}\n';
    }
  }
}
const file = path.join(dir, 'dark.css');
if (process.argv[2] === 'check') {
  if (fs.readFileSync(file, 'utf8') !== out) { console.error('css/dark.css is out of date: run node scripts/dark-css.js'); process.exit(1); }
  console.log('css/dark.css is up to date');
} else { fs.writeFileSync(file, out); console.log('wrote css/dark.css'); }
